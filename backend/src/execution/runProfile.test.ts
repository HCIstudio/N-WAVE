import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { assertCanSubmitToSlurm } from "./nextflowLauncher";
import { buildScriptRunFiles, MODULE_CONFIG_FILE, preparePipelineRun } from "./prepareRun";
import { createRunDirectories } from "./runDirectory";
import { buildRunProfileConfig, runProfileSchema } from "./runProfile";

const slurm = runProfileSchema.parse({
  name: "slurm",
  executor: "slurm",
  queue: "short",
  containerEngine: "singularity",
  cpus: 2,
  memory: "4 GB",
  time: "2h",
  clusterOptions: "--account=lab",
  queueSize: 20,
});

describe("run profiles", () => {
  it("builds a SLURM profile's config", () => {
    expect(buildRunProfileConfig(slurm).split("\n")).toEqual([
      '// Generated by N-WAVE: the run profile "slurm".',
      "process.executor = 'slurm'",
      "process.queue = 'short'",
      "process.clusterOptions = '--account=lab'",
      "process.cpus = 2",
      "process.memory = '4 GB'",
      "process.time = '2h'",
      "executor.queueSize = 20",
      "docker.enabled = false",
      "singularity.enabled = true",
      "singularity.autoMounts = true",
    ]);
  });

  it.each([
    ["a quote in the sbatch options", { clusterOptions: "--account='x'" }],
    ["a line break in the sbatch options", { clusterOptions: "a\nprocess.executor = 'local'" }],
    ["a queue with spaces", { queue: "short; rm" }],
    ["a name with a dash", { name: "my-slurm" }],
    ["an unknown engine", { containerEngine: "podman" }],
    ["AWS Batch", { executor: "awsbatch" }],
    ["memory in words", { memory: "a lot" }],
  ])("refuses %s", (_label, change) => {
    expect(runProfileSchema.safeParse({ ...slurm, ...change }).success).toBe(false);
  });

  it("puts the profile last in a script run's config, with its containers", () => {
    const run = buildScriptRunFiles("workflow {\n}\n", {
      useDocker: true,
      resourceConfig: "process.resourceLimits = [cpus: 2]",
      profile: slurm,
    });
    expect(run.prepared.useProcessDocker).toBe(false);
    expect(run.config.indexOf("resourceLimits")).toBeLessThan(run.config.indexOf("process.executor = 'slurm'"));
    // Without a profile, Docker stays as chosen.
    expect(
      buildScriptRunFiles("workflow {\n}\n", { useDocker: true, resourceConfig: "" }).prepared.useProcessDocker,
    ).toBe(true);
    const withDocker = buildScriptRunFiles("workflow {\n}\n", {
      useDocker: false,
      resourceConfig: "",
      profile: { ...slurm, containerEngine: "docker" },
    });
    expect(withDocker.prepared.useProcessDocker).toBe(true);
    // The local executor N-WAVE sets for Docker runs comes first, so SLURM wins.
    expect(withDocker.config.lastIndexOf("executor = 'local'")).toBeLessThan(
      withDocker.config.indexOf("process.executor = 'slurm'"),
    );
  });

  describe("pipelines", () => {
    let root: string;
    beforeEach(() => {
      root = fs.mkdtempSync(path.join(os.tmpdir(), "nwave-profile-"));
    });
    afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

    it("adds the profile to a pipeline run's config", () => {
      const dirs = createRunDirectories(root, "run");
      const prepared = preparePipelineRun(
        dirs,
        { name: "rnaseq", version: "3.27.0", profiles: ["test", "docker"], params: {} },
        "limits",
        slurm,
      );
      expect(prepared.useProcessDocker).toBe(false);
      const config = fs.readFileSync(path.join(dirs.main, MODULE_CONFIG_FILE), "utf8");
      expect(config.startsWith("limits\n\n// Generated by N-WAVE: the run profile")).toBe(true);
      expect(config).toContain("singularity.enabled = true");
    });
  });

  it("needs Nextflow on this server and sbatch to submit to SLURM", async () => {
    await expect(assertCanSubmitToSlurm(false, async () => true)).rejects.toThrow(
      "NEXTFLOW_EXECUTION_MODE=local",
    );
    await expect(assertCanSubmitToSlurm(true, async () => false)).rejects.toThrow("needs sbatch");
    await expect(assertCanSubmitToSlurm(true, async () => true)).resolves.toBeUndefined();
  });
});

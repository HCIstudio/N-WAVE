// A run through a run profile (Execution Settings → Profiles): the config
// that sends its steps to SLURM (or keeps them on this computer) with the
// profile's containers and default resources. Built here from validated
// fields, never from config text the browser sends. Mirrors
// frontend/src/execution/runProfiles.ts, which writes the same settings into
// exported projects.

import { z } from "zod";

const memory = z.string().regex(/^\d+(\.\d+)?\s*\.?\s*(KB|MB|GB|TB)$/i).max(32);

export const runProfileSchema = z
  .object({
    name: z.string().regex(/^[A-Za-z][A-Za-z0-9_]{0,39}$/),
    executor: z.enum(["local", "slurm", "awsbatch"]),
    queue: z.string().regex(/^[A-Za-z0-9_.:/@-]{1,256}$/).optional(),
    containerEngine: z.enum(["docker", "singularity", "apptainer", "none"]),
    cpus: z.number().int().min(1).max(1_024).optional(),
    memory: memory.optional(),
    time: z.string().regex(/^\d+(\.\d+)?\s*(s|m|h|d)$/).max(32).optional(),
    // Written into a single-quoted config string.
    clusterOptions: z.string().regex(/^[^'\\\n\r]{1,500}$/).optional(),
    queueSize: z.number().int().min(1).max(10_000).optional(),
    awsRegion: z.string().max(64).optional(),
    workDir: z.string().max(1_024).optional(),
  })
  .refine((profile) => profile.executor !== "awsbatch", {
    message: "AWS Batch profiles are for exported projects; N-WAVE can't run them itself yet",
    path: ["executor"],
  });

export type RunProfile = z.infer<typeof runProfileSchema>;

const quoted = (value: string): string => `'${value.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

const containerLines: Record<RunProfile["containerEngine"], string[]> = {
  // Docker's own settings come from buildExecutionConfig.
  docker: ["docker.enabled = true"],
  singularity: ["docker.enabled = false", "singularity.enabled = true", "singularity.autoMounts = true"],
  apptainer: ["docker.enabled = false", "apptainer.enabled = true", "apptainer.autoMounts = true"],
  none: ["docker.enabled = false"],
};

/**
 * The run's config for a profile. It goes last in the run's config, so it
 * wins over the local executor N-WAVE sets for Docker runs.
 */
export const buildRunProfileConfig = (profile: RunProfile): string =>
  [
    `// Generated by N-WAVE: the run profile "${profile.name}".`,
    `process.executor = ${quoted(profile.executor)}`,
    ...(profile.queue ? [`process.queue = ${quoted(profile.queue)}`] : []),
    ...(profile.executor === "slurm" && profile.clusterOptions
      ? [`process.clusterOptions = ${quoted(profile.clusterOptions)}`]
      : []),
    ...(profile.cpus !== undefined ? [`process.cpus = ${profile.cpus}`] : []),
    ...(profile.memory ? [`process.memory = ${quoted(profile.memory.trim())}`] : []),
    ...(profile.time ? [`process.time = ${quoted(profile.time.trim())}`] : []),
    ...(profile.queueSize !== undefined ? [`executor.queueSize = ${profile.queueSize}`] : []),
    ...containerLines[profile.containerEngine],
  ].join("\n");

/** Whether the run's steps run in Docker containers. */
export const profileUsesDocker = (profile: RunProfile): boolean => profile.containerEngine === "docker";
